/**
 * LUXESTORE — Build Products Script
 * 
 * Ce script scanne automatiquement les dossiers assets/productX/
 * et génère le fichier products-data.js avec toutes les images et vidéos.
 * 
 * USAGE: node build-products.js
 * 
 * Workflow:
 * 1. Créer un dossier assets/product7/ (par exemple)
 * 2. Y mettre vos images (.jpg, .jpeg, .png, .webp) et vidéos (.mp4)
 * 3. Ajouter les infos dans products-config.json (nom, prix, description)
 * 4. Lancer: node build-products.js
 * 5. Rafraîchir le navigateur — le produit apparaît automatiquement!
 */

const fs = require('fs');
const path = require('path');

const ASSETS_DIR = path.join(__dirname, 'assets');
const CONFIG_FILE = path.join(__dirname, 'products-config.json');
const OUTPUT_FILE = path.join(__dirname, 'products-data.js');

const IMAGE_EXTS = ['.jpg', '.jpeg', '.png', '.webp', '.gif'];
const VIDEO_EXTS = ['.mp4', '.webm', '.mov'];

// Load config
let config = {};
if (fs.existsSync(CONFIG_FILE)) {
  config = JSON.parse(fs.readFileSync(CONFIG_FILE, 'utf8'));
}

// Scan assets directory for productX folders
const folders = fs.readdirSync(ASSETS_DIR)
  .filter(f => f.startsWith('product') && fs.statSync(path.join(ASSETS_DIR, f)).isDirectory())
  .sort((a, b) => {
    const numA = parseInt(a.replace('product', '')) || 0;
    const numB = parseInt(b.replace('product', '')) || 0;
    return numA - numB;
  });

const products = [];
const defaultBadges = ['🔥 Best Seller', '⚡ Tendance', '🆕 Nouveau', '📸 Viral TikTok', '⭐ Premium', '💼 Setup', '🎯 Top Vente', '💎 Exclusif'];

folders.forEach((folder, index) => {
  const folderPath = path.join(ASSETS_DIR, folder);
  const files = fs.readdirSync(folderPath);

  // Separate images and videos
  const images = files
    .filter(f => IMAGE_EXTS.includes(path.extname(f).toLowerCase()))
    .map(f => `assets/${folder}/${f}`);

  const videos = files
    .filter(f => VIDEO_EXTS.includes(path.extname(f).toLowerCase()))
    .map(f => `assets/${folder}/${f}`);

  // Skip folders with no media
  if (images.length === 0 && videos.length === 0) {
    console.log(`⏭️  ${folder}/ — Aucun média trouvé, ignoré.`);
    return;
  }

  // Get config or use defaults
  const cfg = config[folder] || {};
  const id = index + 1;

  const product = {
    id: id,
    name: cfg.name || `Produit ${id}`,
    desc: cfg.desc || `Produit tendance de qualité premium. Livraison rapide au Maroc.`,
    price: cfg.price || 99,
    oldPrice: cfg.oldPrice || 199,
    badge: cfg.badge || defaultBadges[index % defaultBadges.length],
    folder: folder,
    images: images,
    video: videos.length > 0 ? videos[0] : null
  };

  products.push(product);
  console.log(`✅ ${folder}/ — ${images.length} image(s), ${videos.length} vidéo(s) → "${product.name}" (${product.price} MAD)`);
});

// Generate output JS
const output = `/* Auto-generated by build-products.js — NE PAS MODIFIER MANUELLEMENT */
/* Dernière mise à jour: ${new Date().toLocaleString('fr-FR')} */
const products = ${JSON.stringify(products, null, 2)};
`;

fs.writeFileSync(OUTPUT_FILE, output, 'utf8');

console.log(`\n🎉 ${products.length} produit(s) générés dans products-data.js`);
console.log(`📂 Rafraîchissez votre navigateur pour voir les changements!`);
